# 4. Model: Heterogeneous GraphSAGE
# =========================================================

RELATIONS = [
    ("user", "open_pr", "repo"),
    ("user", "open_issue", "repo"),
    ("user", "issue_comment", "repo"),
    ("user", "pr_review", "repo"),
    ("user", "pr_review_comment", "repo"),
    ("user", "push", "repo"),

    ("repo", "rev_open_pr", "user"),
    ("repo", "rev_open_issue", "user"),
    ("repo", "rev_issue_comment", "user"),
    ("repo", "rev_pr_review", "user"),
    ("repo", "rev_pr_review_comment", "user"),
    ("repo", "rev_push", "user"),
]


class HeteroGraphSAGE(nn.Module):
    def __init__(self, hidden_channels=32, dropout=0.3):
        super().__init__()

        self.conv1 = HeteroConv(
            {
                rel: SAGEConv(
                    (-1, -1),
                    hidden_channels,
                )
                for rel in RELATIONS
            },
            aggr="sum",
        )

        self.conv2 = HeteroConv(
            {
                rel: SAGEConv(
                    (-1, -1),
                    hidden_channels,
                )
                for rel in RELATIONS
            },
            aggr="sum",
        )

        self.user_norm1 = nn.LayerNorm(hidden_channels)
        self.repo_norm1 = nn.LayerNorm(hidden_channels)

        self.user_norm2 = nn.LayerNorm(hidden_channels)
        self.repo_norm2 = nn.LayerNorm(hidden_channels)

        self.dropout = dropout

        self.classifier = nn.Sequential(
            nn.Linear(hidden_channels, hidden_channels),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_channels, 6),
        )

    def forward(self, data):
        x_dict = {
            "user": data["user"].x,
            "repo": data["repo"].x,
        }

        # First graph convolution.
        x_dict = self.conv1(
            x_dict,
            data.edge_index_dict,
        )

        x_dict["user"] = F.relu(
            self.user_norm1(x_dict["user"])
        )

        x_dict["repo"] = F.relu(
            self.repo_norm1(x_dict["repo"])
        )

        x_dict = {
            key: F.dropout(
                value,
                p=self.dropout,
                training=self.training,
            )
            for key, value in x_dict.items()
        }

        # Second graph convolution.
        x_dict = self.conv2(
            x_dict,
            data.edge_index_dict,
        )

        x_dict["user"] = F.relu(
            self.user_norm2(x_dict["user"])
        )

        x_dict["repo"] = F.relu(
            self.repo_norm2(x_dict["repo"])
        )

        # Predict six activities for user nodes.
        logits = self.classifier(x_dict["user"])

        return logits


# 5. Threshold calibration
#    Train on first 4 snapshots, calibrate on last 2.

CAL_TRAIN_GRAPHS = train_graphs[:4]
CAL_VALID_GRAPHS = train_graphs[4:]

# Calculate normalization statistics using calibration training data only.
cal_user_train = torch.cat(
    [g["data"]["user"].x for g in CAL_TRAIN_GRAPHS],
    dim=0,
)

cal_repo_train = torch.cat(
    [g["data"]["repo"].x for g in CAL_TRAIN_GRAPHS],
    dim=0,
)

cal_user_mean = cal_user_train.mean(dim=0)
cal_user_std = cal_user_train.std(dim=0).clamp(min=1e-6)

cal_repo_mean = cal_repo_train.mean(dim=0)
cal_repo_std = cal_repo_train.std(dim=0).clamp(min=1e-6)


def normalize_cal_graph(graph_result):
    data = graph_result["data"].clone()

    data["user"].x = (
        data["user"].x - cal_user_mean
    ) / cal_user_std

    data["repo"].x = (
        data["repo"].x - cal_repo_mean
    ) / cal_repo_std

    return data


cal_train_data = [
    normalize_cal_graph(g) for g in CAL_TRAIN_GRAPHS
]

cal_valid_data = [
    normalize_cal_graph(g) for g in CAL_VALID_GRAPHS
]

# Calculate class weights from calibration training data.
cal_train_y = torch.cat(
    [d["user"].y for d in cal_train_data],
    dim=0,
)

cal_positive = cal_train_y.sum(dim=0)
cal_negative = len(cal_train_y) - cal_positive

cal_pos_weight = (
    cal_negative / cal_positive.clamp(min=1)
).clamp(max=20.0)


# Train a separate model for threshold calibration.
torch.manual_seed(SEED)
np.random.seed(SEED)

cal_model = HeteroGraphSAGE(
    hidden_channels=HIDDEN_CHANNELS,
    dropout=DROPOUT,
).to(DEVICE)

cal_optimizer = torch.optim.Adam(
    cal_model.parameters(),
    lr=LEARNING_RATE,
    weight_decay=WEIGHT_DECAY,
)

cal_criterion = nn.BCEWithLogitsLoss(
    pos_weight=cal_pos_weight
)

# Select the best epoch using calibration snapshots only.
CAL_MAX_EPOCHS = 30
CAL_PATIENCE = 5

cal_best_score = -1
cal_best_epoch = 0
cal_best_state = None
cal_wait = 0

for epoch in range(1, CAL_MAX_EPOCHS + 1):
    cal_model.train()
    total_loss = 0

    for data in cal_train_data:
        cal_optimizer.zero_grad()

        logits = cal_model(data)
        labels = data["user"].y

        loss = cal_criterion(logits, labels)
        loss.backward()

        torch.nn.utils.clip_grad_norm_(
            cal_model.parameters(),
            max_norm=1.0,
        )

        cal_optimizer.step()
        total_loss += loss.item()

    # Evaluate calibration snapshots at threshold 0.5.
    cal_model.eval()

    epoch_true = []
    epoch_pred = []

    with torch.no_grad():
        for data in cal_valid_data:
            logits = cal_model(data)
            probabilities = torch.sigmoid(logits)

            epoch_true.append(
                data["user"].y.cpu().numpy()
            )

            epoch_pred.append(
                (probabilities >= 0.5).int().cpu().numpy()
            )

    epoch_true = np.concatenate(epoch_true, axis=0)
    epoch_pred = np.concatenate(epoch_pred, axis=0)

    cal_macro = f1_score(
        epoch_true,
        epoch_pred,
        average="macro",
        zero_division=0,
    )

    cal_micro = f1_score(
        epoch_true,
        epoch_pred,
        average="micro",
        zero_division=0,
    )

    cal_combined = (cal_macro + cal_micro) / 2

    print(
        f"Calibration Epoch {epoch:02d} | "
        f"Loss {total_loss / len(cal_train_data):.4f} | "
        f"Macro {cal_macro:.4f} | "
        f"Micro {cal_micro:.4f} | "
        f"Combined {cal_combined:.4f}"
    )

    if cal_combined > cal_best_score:
        cal_best_score = cal_combined
        cal_best_epoch = epoch
        cal_best_state = copy.deepcopy(
            cal_model.state_dict()
        )
        cal_wait = 0
    else:
        cal_wait += 1

    if cal_wait >= CAL_PATIENCE:
        print("Calibration early stopping.")
        break

# Restore the best calibration model.
cal_model.load_state_dict(cal_best_state)

print("\nCalibration best epoch:", cal_best_epoch)
print(f"Calibration best Combined F1: {cal_best_score:.4f}")

# Collect probabilities using the best calibration model.
cal_model.eval()

cal_true_list = []
cal_prob_list = []

with torch.no_grad():
    for data in cal_valid_data:
        logits = cal_model(data)
        probabilities = torch.sigmoid(logits)

        cal_true_list.append(
            data["user"].y.cpu().numpy()
        )

        cal_prob_list.append(
            probabilities.cpu().numpy()
        )

cal_y_true = np.concatenate(cal_true_list, axis=0)
cal_y_prob = np.concatenate(cal_prob_list, axis=0)

# Find an independent threshold for each activity.
threshold_grid = np.arange(0.05, 0.951, 0.01)
calibrated_thresholds = []

for j, label in enumerate(LABEL_NAMES):
    best_threshold = 0.5
    best_f1 = -1

    for threshold in threshold_grid:
        pred = (
            cal_y_prob[:, j] >= threshold
        ).astype(int)

        score = f1_score(
            cal_y_true[:, j],
            pred,
            zero_division=0,
        )

        if (
            score > best_f1
            or (
                np.isclose(score, best_f1)
                and abs(threshold - 0.5)
                < abs(best_threshold - 0.5)
            )
        ):
            best_f1 = score
            best_threshold = threshold

    calibrated_thresholds.append(best_threshold)

calibrated_thresholds = np.array(
    calibrated_thresholds
)

print("\n===== Calibrated Thresholds =====")

for label, threshold in zip(
    LABEL_NAMES,
    calibrated_thresholds,
):
    print(f"{label:20s}: {threshold:.2f}")

