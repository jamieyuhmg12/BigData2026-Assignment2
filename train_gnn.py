# 2. Load graphs

def load_graph(date):
    path = GRAPH_DIR / f"graph_{date}.pt"

    # These graph files are generated by our own script.
    try:
        result = torch.load(
            path,
            map_location=DEVICE,
            weights_only=False,
        )
    except TypeError:
        result = torch.load(path, map_location=DEVICE)

    return result


train_graphs = [load_graph(d) for d in TRAIN_DATES]
valid_graphs = [load_graph(d) for d in VALID_DATES]

print("Training snapshots:", len(train_graphs))
print("Validation snapshots:", len(valid_graphs))


# 3. Feature normalization
#    Statistics are calculated from training snapshots only.

all_user_train = torch.cat(
    [g["data"]["user"].x for g in train_graphs],
    dim=0,
)

all_repo_train = torch.cat(
    [g["data"]["repo"].x for g in train_graphs],
    dim=0,
)

user_mean = all_user_train.mean(dim=0)
user_std = all_user_train.std(dim=0).clamp(min=1e-6)

repo_mean = all_repo_train.mean(dim=0)
repo_std = all_repo_train.std(dim=0).clamp(min=1e-6)


def normalize_graph(graph_result):
    data = graph_result["data"].clone()

    data["user"].x = (
        data["user"].x - user_mean
    ) / user_std

    data["repo"].x = (
        data["repo"].x - repo_mean
    ) / repo_std

    return data


train_data = [normalize_graph(g) for g in train_graphs]
valid_data = [normalize_graph(g) for g in valid_graphs]


